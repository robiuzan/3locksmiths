// Normalize: decode entities + fold curly apostrophes/quotes to straight ' so matching is reliable.
const dec = (s) =>
  he
    .decode(s || "")
    .replace(/[‘’]/g, "'")
    .replace(/\s+/g, " ")
    .trim();

function classify(p) {
  const path = p.path || "";
  const title = dec(p.title);
  if (p.isFront) return null;
  if (path.startsWith("/step/")) return null;
  if (EXCLUDE.has(p.id) || EXCLUDE_PATHS.has(path)) return null;
  // NOTE: id 95 (שכפול מפתח לרכב) used to be excluded here as an "already-rich exemplar,
  // not enriched". That stopped being true on 2026-08-24 when content/enriched/95.mjs was
  // authored — it is now a normal service page and the site's Tier-1 head term, so it must
  // appear in the manifest like any other (footer link lists, related-link candidates).
  // REFERENCE_ID is still the structural reference other modules were written against, and
  // is still pushed into relatedServices below — guarded against self-reference.

  if (path.startsWith(GUIDES_PREFIX)) return { kind: "guide" };

  if (path.startsWith("/locations/")) {
    const city =
      CITIES.find((c) => title.includes(c)) ||
      title.replace(/^שכפול\s+מפתח(?:ות)?\s+ב/, "").trim(); // fallback
    return { kind: "location", city };
  }
  if (path.startsWith("/services/")) {
    const brand = BRANDS.find((b) => title.includes(b));
    return brand ? { kind: "brand-key", brand } : { kind: "service" };
  }
  return { kind: "core" };
}

const rows = [];
for (const p of site.pages) {
  const c = classify(p);
  if (!c) continue;
  rows.push({
    id: p.id,
    kind: c.kind,
    title: dec(p.title),
    keyword: dec(p.title),
    path: p.path,
    canonical: p.seo?.canonical || "",
    ...(c.brand ? { brand: c.brand } : {}),
    ...(c.city ? { city: c.city } : {}),
  });
}

// Attach related-link candidates (ids) to drive the internal-link silo.
const byKind = (k) => rows.filter((r) => r.kind === k);
const brandRows = byKind("brand-key");
const serviceRows = byKind("service");
const locationRows = byKind("location");
const genericServiceLinks = serviceRows.slice(0, 6); // door/lock/generic services
const topLocations = locationRows.slice(0, 6);

for (const r of rows) {
  const relatedServices = [];
  const relatedLocations = [];
  if (r.kind === "brand-key") {
    // 5 sibling brands + parent ref (95) + a couple generic services
    relatedServices.push(
      ...brandRows
        .filter((b) => b.id !== r.id)
        .slice(0, 5)
        .map((b) => b.id),
    );
    if (r.id !== REFERENCE_ID) relatedServices.push(REFERENCE_ID);
  } else if (r.kind === "service") {
    relatedServices.push(
      ...serviceRows
        .filter((s) => s.id !== r.id)
        .slice(0, 5)
        .map((s) => s.id),
    );
    if (r.id !== REFERENCE_ID) relatedServices.push(REFERENCE_ID);
  } else if (r.kind === "location") {
    relatedLocations.push(
      ...locationRows
        .filter((l) => l.id !== r.id)
        .slice(0, 5)
        .map((l) => l.id),
    );
    relatedServices.push(
      ...(r.id !== REFERENCE_ID ? [REFERENCE_ID] : []),
      ...genericServiceLinks.slice(0, 3).map((s) => s.id),
    );
  } else {
    relatedServices.push(
      ...serviceRows.slice(0, 4).map((s) => s.id),
      ...(r.id !== REFERENCE_ID ? [REFERENCE_ID] : []),
    );
    relatedLocations.push(...topLocations.slice(0, 3).map((l) => l.id));
  }
  r.relatedServices = [...new Set(relatedServices)];
  r.relatedLocations = [...new Set(relatedLocations)];
}

// --- duplicate-intent twins ------------------------------------------------------------
// Several head terms exist at BOTH a top-level Hebrew permalink and a /services/ URL --
// e.g. /מנעולן-רכב/ (core) and /services/מנעולן-רכב/, plus מנעולן-לבית, קודן-לרכב and
// שכפול-שלט-לרכב. Both are live WordPress permalinks holding ranking signal, so they are
// never merged (docs/keyword-map.md §8). Instead each twin links to the other, so they read
// as related rather than competing (docs/information-architecture.md §3.2).
//
// This also fixes a real orphan: /שכפול-שלט-לרכב-2/ (the WordPress duplicate-slug suffix)
// had ZERO inbound links sitewide until this edge existed.
const normKeyword = (r) => (r.keyword || r.title || "").replace(/\s+/g, " ").trim();
const byKeyword = new Map();
for (const r of rows) {
  const k = normKeyword(r);
  if (!byKeyword.has(k)) byKeyword.set(k, []);
  byKeyword.get(k).push(r);
}
let twinEdges = 0;
for (const group of byKeyword.values()) {
  if (group.length < 2) continue;
  for (const r of group) {
    for (const twin of group) {
      if (twin.id === r.id) continue;
      if (!r.relatedServices.includes(twin.id)) {
        r.relatedServices.push(twin.id);
        twinEdges++;
      }
    }
  }
}
if (twinEdges) console.log(`twins: linked ${twinEdges} duplicate-intent edge(s)`);

// id -> {path,title} lookup so authors can resolve related ids to label+href.
const lookup = {};
for (const p of site.pages) lookup[p.id] = { path: p.path, title: dec(p.title) };

const manifest = { referenceId: REFERENCE_ID, count: rows.length, lookup, pages: rows };
writeFileSync(
  join(ENRICHED, "_manifest.json"),
  JSON.stringify(manifest, null, 2),
  "utf8",
);

const byK = rows.reduce((a, r) => ((a[r.kind] = (a[r.kind] || 0) + 1), a), {});
console.log(`manifest: ${rows.length} pages →`, byK);
